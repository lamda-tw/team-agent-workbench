def section(source, start, end, body):
    if start not in source:
        return source
    pattern = '(' + re.escape(start) + r'\s*\n(?:### [^\n]+\n)?).*?(?=' + re.escape(end) + ')'
    source, count = re.subn(pattern, lambda m: m[1] + '\n' + body.strip() + '\n\n', source, flags=re.S)
    if count != 1:
        raise ValueError(f'Upload guidance section changed: {start}')
    return source


