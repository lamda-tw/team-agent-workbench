import { _electron as electron, expect as baseExpect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { Workbench } from '../src/core/workbench';
import type { RsiView } from '../src/shared/rsi';
// @ts-expect-error Shared test launcher.
import { authLauncher } from '../tests/fixtures/auth-launcher.mjs';
async function main() {
  const root = process.cwd(), data = path.join(root, '.test-data', 'rsi-ui-' + Date.now()), store = path.join(data, 'user'), output = path.join(data, 'screens'); await fs.mkdir(output, { recursive: true });
  const fixture = await authLauncher(path.join(data, 'cli'), { status: 'ready', turn: 'success', rsi: true, permissionRuntime: true });
  const wb = new Workbench(path.join(store, 'personal'), () => {}, () => {}, undefined, () => ({}), undefined, undefined, undefined, true);
  await wb.store.init(); await wb.restoreLocalWorkspace(); wb.store.settings.providerPaths = { codex: fixture.launcher, cursor: fixture.launcher, claude: fixture.launcher };
  const session = await wb.createSession('codex', data, '__personal__', 'work', undefined, 'gpt-fixture');
  session.messages.push({ id: randomUUID(), role: 'user', text: '开发集实体边界错误，需要做算法研究', createdAt: new Date().toISOString() }); await wb.store.save(); await wb.close();
  const env = { ...process.env, WORKBENCH_TEST: '1', WORKBENCH_DATA_DIR: store }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ args: ['dist/user'], cwd: root, env, timeout: 60000 }), page = await app.firstWindow(), errors: string[] = [];
  const expect = baseExpect.configure({ timeout: 20000 }); page.on('pageerror', error => errors.push(error.message));
  const view = () => page.evaluate(() => window.workbench.call<RsiView>('rsi.view', { projectId: '__personal__' }));
  try {
    await page.getByRole('button', { name: '跳过，暂不登录', exact: true }).click();
    await page.getByRole('button', { name: '项目助手', exact: true }).click();
    const navigation = page.getByRole('button', { name: '项目助手', exact: true });
    assert.equal(await navigation.locator('span').evaluate(element => getComputedStyle(element).whiteSpace), 'nowrap');
    await expect(page.getByRole('heading', { name: '项目助手', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '开启项目助手', exact: true }).click();
    await page.getByRole('button', { name: '分析下一步', exact: true }).click();
    await expect.poll(async () => (await view()).suggestions.length).toBe(1);
    const card = page.locator('.rsi-card').filter({ hasText: '先核对实体边界' }); await expect(card).toBeVisible();
    await card.locator('summary').click(); await expect(card.locator('blockquote')).not.toHaveCount(0);
    await page.screenshot({ path: path.join(output, 'suggestion.png') });
    await card.getByRole('button', { name: '修改建议', exact: true }).click();
    await card.getByLabel('建议反馈').fill('先检查最小反例，再验证 UTF-16 字符偏移。');
    await card.getByRole('button', { name: '保存反馈', exact: true }).click();
    await expect(card).toContainText('再验证 UTF-16');
    await card.getByRole('button', { name: '放入会话输入框', exact: true }).click();
    await expect(page.locator('.rsi-panel')).toHaveCount(0);
    const snapshot = await page.evaluate(() => window.workbench.call<any>('snapshot'));
    assert(snapshot.inputs[session.id].text.includes('再验证 UTF-16')); assert.equal(snapshot.sessions.find((item: any) => item.id === session.id).messages.length, 1);
    assert(!(await view()).events.some(event => event.kind === 'outcome'));
    await page.getByRole('button', { name: '项目助手', exact: true }).click();
    await expect(card).toContainText('已接受，效果待验证');
    await card.getByRole('button', { name: '记录实际结果', exact: true }).click();
    await card.getByLabel('建议反馈').fill('独立评测：开发集 F1 从 0.5 提高到 0.8，尚未检查保留集。');
    await card.getByLabel('实际结果').selectOption('unknown'); await card.getByRole('button', { name: '保存反馈', exact: true }).click();
    await expect(card).toContainText('结果待确认');
    await page.getByRole('button', { name: '策略与验证', exact: true }).click();
    await page.getByRole('button', { name: '从反馈提炼改进', exact: true }).click();
    await expect.poll(async () => (await view()).policies.filter(policy => policy.status === 'candidate').length).toBe(1);
    await expect(page.getByRole('button', { name: '发布此策略', exact: true })).toBeDisabled();
    await page.getByRole('button', { name: '运行独立对照', exact: true }).click();
    await expect(page.getByRole('alert')).toContainText('至少 3 个');
    await page.screenshot({ path: path.join(output, 'policy-gate.png') });
    await page.getByRole('button', { name: '下一步建议', exact: true }).click();
    await card.getByRole('button', { name: '稍后再看', exact: true }).click();
    await expect(card).toContainText('结果待确认');
    await card.getByRole('button', { name: '关闭建议', exact: true }).click(); await expect(card).toHaveCount(0);
    await page.getByLabel('显示已关闭和不适用的建议').check(); await expect(card).toBeVisible();
    await page.getByRole('button', { name: '助手设置', exact: true }).click();
    await page.getByLabel('长期建议偏好（同账号跨项目使用）').fill('优先解释不确定性');
    await page.getByLabel('开启本项目助手').uncheck(); await page.getByRole('button', { name: '保存助手设置', exact: true }).click();
    await expect.poll(async () => (await view()).config.enabled).toBe(false);
    await expect.poll(async () => (await view()).personalPreference).toBe('优先解释不确定性');
    await expect(page.getByRole('button', { name: '分析下一步', exact: true })).toBeDisabled();
    assert.deepEqual(errors, []);
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().some(window => window.isVisible())), false);
    console.log(JSON.stringify({ passed: true, data, cases: ['opt-in', 'navigation-layout', 'edited-adoption', 'explicit-personal-preference', 'real-CLI-protocol-stub', 'evidence-visible', 'accepted-is-not-executed', 'independent-outcome', 'candidate-gate', 'insufficient-cases', 'defer', 'dismiss-and-history', 'disable', 'no-visible-window', 'no-render-errors'] }));
  } finally { await app.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
