"""Keep current collaboration guidance and stable task anchors in the HTML edition."""
import re


def current_guidance(source):
    if source.startswith('# 个人成果分类与任务入口'):
        source = source.replace('## 任务入口', '<a id="classification-reference-tasks"></a>\n\n## 任务入口')
        source = source.replace('## 任务文件', '<a id="classification-reference-task-files"></a>\n\n## 任务文件')
    source = source.replace('从旧源码升级到 5fe696d', '升级已有团队空间')
    source = source.replace('由系统管理员指定创建者', '由总管理员指定创建者')
    source = source.replace('工作台连接共享空间且窗口可见时，每 15 秒检查有权限项目的团队成果。', '连接共享空间后，工作台每 15 秒同步有权限项目的团队成果；窗口最小化后仍继续检查。')
    source = re.sub(r'\*\*会话相关动态提醒。\*\*[^\n]*', '''<a id="activity-recommendations"></a>

### 自动推荐与当前会话相关的动态

同组成员发布了与当前工作有关的成果时，工作台会将它推荐到工作会话的输入框上方，方便你在继续工作前查看和采用。界面示例见[发现并采用相关动态](#case-activity-recommendations)。

**推荐依据与范围。** 工作台用每个未关闭工作会话自己的阶段摘要，判断当前项目新增、修订或合并的团队成果是否相关。推荐使用摘要和新增成果，不读取完整对话或展开所有附件。进入项目时已有的动态用于建立基线，之后出现的新动态才参与判断；自己的变更不推荐给自己。Cursor 原生会话暂不参与。

**出现时机。** 当前轮次结束后，输入框上方显示“新增 N 条可能相关的动态”，点击“查看”展开。正在生成回复时不展开提醒；下次发送前仍有未展示的新推荐，会先打开选择面板，保留已输入的文字。后台尚未完成判断时可以继续发送。

1. 阅读每条的关联理由和原文片段；需要更多依据时点击**查看全文**。
2. 按用途勾选**加入当前会话**、**存入个人成果库**，两项可独立选择，也可同时勾选。默认展开三条，点击**展开其余**查看更多；批量勾选只作用于当前展开的条目。
3. 点击**执行所选**；从发送操作打开面板时，按钮显示**执行所选并发送**，处理完成后继续发送原输入。

| 选择 | 实际效果 |
| --- | --- |
| 加入当前会话 | 将所选成果的版本作为下一条消息的参考资料，不自动保存个人副本 |
| 存入个人成果库 | 保存本人可管理的副本，不自动带入会话 |
| 本会话忽略 | 仅在这一会话忽略这一条动态版本，其他会话仍可独立判断和采用 |
| 本轮跳过，直接发送 | 继续发送原输入，候选保留在推荐入口中，同一批已展示的候选不会每轮重复展开 |

注：推荐供成员选择，成果不会因被推荐就自动加入会话。执行前会重新核对版本和权限，版本变化时提示重新核对；已加入的版本不会静默替换。若显示“新动态判断暂未完成”，可以继续对话，工作台在新动态到达或相关资料、连接恢复后自动续办。
''', source)
    if '<a id="section-4-1"></a>' in source:
        marker = '<a id="section-4-2"></a>'
        journal = '''### 查看项目会话日志

工作台在后台记录项目会话日志。每个未关闭的工作会话保留最近五轮日志，在本轮结束后更新。向模型发送消息时，工作台提供同账号、同项目的日志，详细摘要按需读取；后续只补充变化。Claude Code 会话可从输入区底部的**项目会话日志**查看总览。

注：日志保存在本机，供自己的项目会话相互了解进度。它不会同步成团队成果；带入其他个人会话内容后，接收会话关闭轨迹自动上传，核对内容后可手动上传。

'''
        source = source.replace(marker, journal + marker, 1)
    return source
