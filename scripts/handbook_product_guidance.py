import re


def replace_heading(source, title, body):
    """Update a reference section while retaining its published heading."""
    pattern = r'(^## ' + re.escape(title) + r'\n).*?(?=^## |\Z)'
    updated, count = re.subn(pattern, lambda match: match[1] + '\n' + body.strip() + '\n\n', source, flags=re.S | re.M)
    if count != 1:
        raise ValueError(f'Current reference section changed: {title}')
    return updated


