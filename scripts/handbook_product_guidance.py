def replace_section(source, anchor, next_anchor, body):
    if f'<a id="{anchor}"></a>' not in source:
        return source
    pattern = r'(<a id="' + re.escape(anchor) + r'"></a>\s*\n### [^\n]+\n).*?(?=<a id="' + re.escape(next_anchor) + r'"></a>)'
    updated, count = re.subn(pattern, lambda match: match[1] + '\n' + body.strip() + '\n\n', source, flags=re.S)
    if count != 1:
        raise ValueError(f'Current product section changed: {anchor}')
    return updated


