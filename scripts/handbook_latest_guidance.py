def replace_section(source, start, end, body):
    pattern = '(' + re.escape('<a id="' + start + '"></a>') + r'\s*\n### [^\n]+\n).*?(?=' + re.escape('<a id="' + end + '"></a>') + ')'
    source, count = re.subn(pattern, lambda m: m[1] + '\n' + body.strip() + '\n\n', source, flags=re.S)
    if count != 1:
        raise ValueError('Handbook section changed: ' + start)
    return source


